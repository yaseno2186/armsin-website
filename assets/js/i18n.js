function initI18n() {
  var STORAGE_KEY = 'armsin-lang';
  var textEls = document.querySelectorAll('[data-i18n]');
  var ariaEls = document.querySelectorAll('[data-i18n-aria]');
  var titleEls = document.querySelectorAll('[data-i18n-title]');
  var langBtns = document.querySelectorAll('.lang-btn');
  if (!textEls.length && !ariaEls.length && !titleEls.length && !langBtns.length) return;

  textEls.forEach(function (el) {
    el.dataset.de = el.tagName === 'META' ? el.getAttribute('content') : el.textContent;
  });
  ariaEls.forEach(function (el) {
    el.dataset.deAria = el.getAttribute('aria-label');
  });
  titleEls.forEach(function (el) {
    el.dataset.deTitle = el.getAttribute('title');
  });

  function apply(lang) {
    document.documentElement.lang = lang;
    textEls.forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var text = (lang === 'en' && I18N_EN[key]) || el.dataset.de;
      if (el.tagName === 'META') el.setAttribute('content', text);
      else el.textContent = text;
    });
    ariaEls.forEach(function (el) {
      var key = el.getAttribute('data-i18n-aria');
      el.setAttribute('aria-label', (lang === 'en' && I18N_EN[key]) || el.dataset.deAria);
    });
    titleEls.forEach(function (el) {
      var key = el.getAttribute('data-i18n-title');
      el.setAttribute('title', (lang === 'en' && I18N_EN[key]) || el.dataset.deTitle);
    });
    langBtns.forEach(function (btn) {
      btn.classList.toggle('is-active', btn.dataset.lang === lang);
    });
  }

  langBtns.forEach(function (btn) {
    btn.addEventListener('click', function () {
      localStorage.setItem(STORAGE_KEY, btn.dataset.lang);
      apply(btn.dataset.lang);
    });
  });

  apply(localStorage.getItem(STORAGE_KEY) || 'de');
}

initI18n();
